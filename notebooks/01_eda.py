# %%
# ?? Cell 1: Setup ??????????????????????????????????????????????????????????
import sys
from pathlib import Path
sys.path.insert(0, str(Path.cwd().parent))  # adjust if running from repo root

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

from src.config import (
    DATASET_PATH, ALL_FEATURES, TARGET_COL,
    TIME_COL, AMOUNT_COL, PCA_FEATURES,
)
from src.data_loader import check_dataset_present, load_dataset

print("Dataset path:", DATASET_PATH)
print("Dataset present:", check_dataset_present())

# %%
# ?? Cell 2: Load dataset ???????????????????????????????????????????????????
if not check_dataset_present():
    print(
        "\nDataset not found. Download from Kaggle:\n"
        "https://www.kaggle.com/datasets/mlg-ulb/creditcardfraud\n"
        "Place at: data/creditcard.csv"
    )
else:
    df = load_dataset()
    print(f"Shape: {df.shape}")
    df.head()

# %%
# ?? Cell 3: Basic info ?????????????????????????????????????????????????????
df.info()

# %%
# ?? Cell 4: Descriptive statistics ?????????????????????????????????????????
df.describe().round(3)

# %%
# ?? Cell 5: Missing values and duplicates ??????????????????????????????????
print("Missing values per column:")
print(df.isnull().sum())
print(f"\nTotal duplicates: {df.duplicated().sum()}")

# %%
# ?? Cell 6: Class imbalance ????????????????????????????????????????????????
fraud_count = df[TARGET_COL].sum()
legit_count = len(df) - fraud_count
print(f"Fraud  : {fraud_count:,}  ({fraud_count/len(df)*100:.3f}%)")
print(f"Legit  : {legit_count:,}  ({legit_count/len(df)*100:.3f}%)")
print(f"Ratio  : 1 : {legit_count // fraud_count}")

df[TARGET_COL].value_counts().plot(kind="bar", color=["#2980b9", "#c0392b"])
plt.title("Class Distribution")
plt.xticks([0, 1], ["Legitimate", "Fraud"], rotation=0)
plt.ylabel("Count")
plt.tight_layout()
plt.show()

# %%
# ?? Cell 7: Amount distribution by class ???????????????????????????????????
fig, axes = plt.subplots(1, 2, figsize=(12, 4))
for cls, color, label in [(0, "#2980b9", "Legit"), (1, "#c0392b", "Fraud")]:
    axes[0].hist(
        np.log1p(df.loc[df[TARGET_COL] == cls, AMOUNT_COL]),
        bins=60, alpha=0.6, color=color, label=label
    )
axes[0].set_title("Transaction Amount by Class (log scale)")
axes[0].set_xlabel("log(Amount + 1)")
axes[0].legend()

df.groupby(TARGET_COL)[AMOUNT_COL].describe()

# %%
# ?? Cell 8: Correlation heatmap ????????????????????????????????????????????
sample = df.sample(min(5000, len(df)), random_state=42)
corr = sample[ALL_FEATURES + [TARGET_COL]].corr()
plt.figure(figsize=(15, 12))
mask = np.triu(np.ones_like(corr, dtype=bool))
sns.heatmap(corr, mask=mask, cmap="coolwarm", center=0, annot=False, linewidths=0.3)
plt.title("Feature Correlation Heatmap")
plt.tight_layout()
plt.show()

# %%
# ?? Cell 9: Feature-vs-target boxplots ?????????????????????????????????????
from scripts.run_eda import plot_feature_vs_target_boxplots
from src.config import EDA_RESULTS_DIR
EDA_RESULTS_DIR.mkdir(parents=True, exist_ok=True)
plot_feature_vs_target_boxplots(df, EDA_RESULTS_DIR)
plt.show()

