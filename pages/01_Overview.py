"""
FraudGuard AI ? Page 1: Overview

Displays:
- Dataset KPI cards (rows, fraud count, fraud rate, features)
- Class distribution chart
- Amount and time distribution chart
- Correlation heatmap
- Top feature boxplots

All charts are loaded from results/eda/ (generated by scripts/run_eda.py).
Statistics come from the saved EDA summary JSON ? never from live re-computation.
"""

import json
import sys
from pathlib import Path

import streamlit as st

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from src.config import EDA_RESULTS_DIR, RESULTS_DIR

st.set_page_config(page_title="Overview ? FraudGuard AI", layout="wide")

# ---------------------------------------------------------------------------
# CSS
# ---------------------------------------------------------------------------
st.markdown(
    """
    <style>
    h1, h2, h3 { color: #1a3a5c; }
    [data-testid="metric-container"] {
        background: #fff;
        border: 1px solid #dde3ee;
        border-radius: 8px;
        padding: 16px 20px;
        box-shadow: 0 1px 4px rgba(0,0,0,0.06);
    }
    </style>
    """,
    unsafe_allow_html=True,
)

# ---------------------------------------------------------------------------
# Header
# ---------------------------------------------------------------------------
st.title("Dataset Overview")
st.markdown(
    "Summary statistics and EDA charts generated from the "
    "**ULB Credit Card Fraud Detection dataset**."
)
st.caption(
    "Source: Kaggle ? Machine Learning Group, Universit? Libre de Bruxelles (ULB). "
    "All charts and statistics are derived from the actual dataset."
)
st.markdown("---")

# ---------------------------------------------------------------------------
# Load EDA summary
# ---------------------------------------------------------------------------
eda_summary_path = EDA_RESULTS_DIR / "eda_summary.json"

if not eda_summary_path.exists():
    st.warning(
        "EDA summary not found. Please run the EDA script first:\n\n"
        "```\npython scripts/run_eda.py\n```",
        icon=None,
    )
    st.stop()

with eda_summary_path.open() as f:
    summary = json.load(f)

# ---------------------------------------------------------------------------
# KPI Cards
# ---------------------------------------------------------------------------
st.subheader("Dataset at a Glance")
c1, c2, c3, c4, c5 = st.columns(5)

c1.metric("Total Transactions", f"{summary['n_rows']:,}")
c2.metric("Fraud Cases", f"{summary['fraud_count']:,}")
c3.metric("Legitimate Cases", f"{summary['legit_count']:,}")
c4.metric(
    "Fraud Rate",
    f"{summary['fraud_pct']:.3f}%",
    delta=None,
    help="Percentage of transactions labelled as fraudulent.",
)
c5.metric(
    "Imbalance Ratio",
    f"1 : {summary['imbalance_ratio']:.0f}",
    help="Ratio of legitimate to fraud transactions.",
)

col_a, col_b, col_c = st.columns(3)
col_a.metric("Columns (features + target)", summary["n_cols"])
col_b.metric("Missing Values", summary["n_missing"])
col_c.metric("Duplicate Rows", summary["n_duplicates"])

st.markdown("---")

# ---------------------------------------------------------------------------
# Dataset description
# ---------------------------------------------------------------------------
st.subheader("Dataset Description")
with st.expander("Feature Details", expanded=True):
    st.markdown(
        """
        | Column | Type | Description |
        |--------|------|-------------|
        | **Time** | float | Seconds elapsed since the first transaction in the dataset |
        | **Amount** | float | Transaction amount in euros |
        | **V1 ? V28** | float | Principal components from PCA (anonymized; original features confidential) |
        | **Class** | int | Target label: **0** = legitimate, **1** = fraud |

        > **Note**: V1-V28 are PCA-transformed components of the original transaction
        > features. Their original meanings are confidential and have not been published.
        > We do not infer or invent their semantics.
        """
    )

# ---------------------------------------------------------------------------
# Observations
# ---------------------------------------------------------------------------
st.subheader("Key Observations")
obs = summary.get("observations", {})

col1, col2 = st.columns(2)
with col1:
    if "class_imbalance" in obs:
        st.markdown(
            f"**Class Imbalance**: {obs['class_imbalance']}"
        )
    if "missing_data" in obs:
        st.markdown(f"**Missing Data**: {obs['missing_data']}")

with col2:
    if "duplicates" in obs:
        st.markdown(f"**Duplicates**: {obs['duplicates']}")
    # Amount statistics
    amount_stats = summary.get("amount_stats", {})
    if amount_stats:
        legit = amount_stats.get("legitimate", {})
        fraud = amount_stats.get("fraud", {})
        st.markdown(
            f"**Amount ? Legitimate**: mean ?{legit.get('mean',0):.2f}, "
            f"median ?{legit.get('median',0):.2f}, max ?{legit.get('max',0):.2f}"
        )
        st.markdown(
            f"**Amount ? Fraud**: mean ?{fraud.get('mean',0):.2f}, "
            f"median ?{fraud.get('median',0):.2f}, max ?{fraud.get('max',0):.2f}"
        )

st.markdown("---")

# ---------------------------------------------------------------------------
# Charts
# ---------------------------------------------------------------------------
st.subheader("EDA Charts")

def show_chart(path: Path, caption: str, col=None):
    """Helper to display a chart if it exists."""
    target = col or st
    if path.exists():
        target.image(str(path), caption=caption, use_container_width=True)
    else:
        target.info(f"Chart not found: {path.name}. Run `python scripts/run_eda.py`.")

# Row 1: Class distribution
show_chart(
    EDA_RESULTS_DIR / "class_distribution.png",
    "Class Distribution ? Legitimate vs Fraud Transactions",
)

st.markdown("---")

# Row 2: Amount and Time
show_chart(
    EDA_RESULTS_DIR / "amount_time_distributions.png",
    "Amount and Time Feature Distributions by Class",
)

st.markdown("---")

# Row 3: Heatmap and Boxplots
col_left, col_right = st.columns([1, 1])
show_chart(
    EDA_RESULTS_DIR / "correlation_heatmap.png",
    "Feature Correlation Heatmap",
    col_left,
)
show_chart(
    EDA_RESULTS_DIR / "feature_vs_target_boxplots.png",
    "Top PCA Feature Distributions by Class",
    col_right,
)

st.markdown("---")
st.caption(
    "Charts generated by `scripts/run_eda.py` using the complete ULB dataset. "
    "Statistics are actual outputs ? not fabricated or illustrative values."
)
